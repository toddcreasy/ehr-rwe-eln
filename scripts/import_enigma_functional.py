"""Transcribe ENIGMA's calibrated functional assay results for BRCA1 and BRCA2 (PS3 and BS3).

Usage: uv run python scripts/import_enigma_functional.py

Downloads Specifications Table 9, v1.2, of the ClinGen ENIGMA BRCA1 and BRCA2 Variant Curation
Expert Panel from the CSpec registry, and writes src/ehr_rwe_eln/curation/enigma_functional.tsv:
one row per variant with the code the panel assigns from calibrated assays (PS3: damaging,
BS3: no damaging effect, None: inconclusive), its strength, and the panel's standard text naming
the studies. ClinGen curated content is CC0 1.0; the file's first lines attribute it with the
date accessed. Run once per new version of the table.
"""

import csv
import urllib.request
from datetime import date
from io import BytesIO
from pathlib import Path

import openpyxl

VERSION = "1.2"
URL = "https://cspec.genome.network/cspec/File/id/0a35d6a8-5050-44b6-8a9d-babe8cdc06b2/data"
DOC = "https://cspec.genome.network/cspec/ui/svi/doc/GN092"
OUT = Path(__file__).resolve().parent.parent / "src/ehr_rwe_eln/curation/enigma_functional.tsv"
SHEET = "Table9_BRCA12VCEP_specs"
COLUMNS = ["gene", "hgvsc", "hgvsp", "code", "strength", "text"]
STRENGTH = {"Strong": "strong", "Moderate": "moderate", "Supporting": "supporting", "N/A": ""}


def main() -> None:
    with urllib.request.urlopen(URL) as response:  # noqa: S310  (fixed https URL)
        book = openpyxl.load_workbook(BytesIO(response.read()), read_only=True)
    rows = []
    for row in book[SHEET].iter_rows(values_only=True):
        cells = [str(c).strip() if c is not None else "" for c in row]
        # Data rows start with the gene; the title, notes, and two header rows do not.
        if cells[0] not in ("BRCA1", "BRCA2") or not cells[1].startswith("c."):
            continue
        rows.append(
            {
                "gene": cells[0],
                "hgvsc": cells[1],
                "hgvsp": cells[2],
                "code": cells[3],
                "strength": STRENGTH[cells[4]],
                "text": " ".join(cells[5].split()),
            }
        )
    with OUT.open("w", newline="") as f:
        f.write(
            f"# ENIGMA BRCA1 and BRCA2 VCEP, Specifications Table 9, v{VERSION}: PS3 and BS3 from\n"
            f"# calibrated functional assays. Source: {DOC} (file {URL}).\n"
            "# Curated content of the Clinical Genome Resource (www.clinicalgenome.org),\n"
            f"# CC0 1.0, accessed {date.today():%Y-%m-%d}.\n"
            "# Generated by scripts/import_enigma_functional.py.\n"
        )
        writer = csv.DictWriter(f, COLUMNS, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(sorted(rows, key=lambda r: (r["gene"], r["hgvsc"])))
    counts: dict = {}
    for r in rows:
        counts[(r["code"], r["strength"])] = counts.get((r["code"], r["strength"]), 0) + 1
    print(f"{len(rows)} variants: {counts}")
    print(f"written to {OUT}")


if __name__ == "__main__":
    main()
