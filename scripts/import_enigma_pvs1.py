"""Transcribe ENIGMA's PVS1 decision table for BRCA1 and BRCA2 into YAML for the curation rules.

Usage: uv run python scripts/import_enigma_pvs1.py

Downloads Specifications Table 4, v1.2, of the ClinGen ENIGMA BRCA1 and BRCA2 Variant Curation
Expert Panel from the CSpec registry, and writes src/ehr_rwe_eln/curation/enigma_pvs1.yaml:
per exon (MANE Select numbering), the PVS1 code for variants that introduce a premature
termination codon (PTC) and the panel's exon-specific PM5_PTC weight; per canonical splice-site
change (+1, +2, -1, -2), its code. ClinGen curated content is CC0 1.0; the YAML attributes it
with the date accessed, as ClinGen asks. Run once per new version of the table.
"""

import re
import urllib.request
from datetime import date
from io import BytesIO
from pathlib import Path

import openpyxl
import yaml

VERSION = "1.2"
URL = "https://cspec.genome.network/cspec/File/id/ca5cf57b-94df-4ad6-a001-c62ceccb3845/data"
DOC = "https://cspec.genome.network/cspec/ui/svi/doc/GN092"
OUT = Path(__file__).resolve().parent.parent / "src/ehr_rwe_eln/curation/enigma_pvs1.yaml"
# Column positions in the sheet "Table 4 - Annotated Exons".
GENE, EXON, NOTE_LEFT, CODE_LEFT, SITE_LEFT, ALLELES_LEFT = 0, 1, 2, 3, 4, 5
PTC_CODE, PTC_TAG, PM5_CODE = 9, 10, 11
SITE_RIGHT, ALLELES_RIGHT, CODE_RIGHT, NOTE_RIGHT = 15, 16, 17, 18


def code(text: str) -> dict:
    """'PVS1_Strong (RNA)' -> strength strong, rna true; 'PVS1_N/A' -> strength None."""
    text = text.strip()
    rna = "(RNA)" in text
    base = text.replace("(RNA)", "").replace("(PTC)", "").strip()
    name, _, level = base.partition("_")
    strength = {
        "": {"PVS1": "very_strong", "PM5": "moderate"}[name],
        "Strong": "strong",
        "Moderate": "moderate",
        "Supporting": "supporting",
        "N/A": None,
    }[level]
    return {"code": text, "strength": strength} | ({"rna": True} if rna else {})


def main() -> None:
    with urllib.request.urlopen(URL) as response:  # noqa: S310  (fixed https URL)
        book = openpyxl.load_workbook(BytesIO(response.read()), read_only=True)
    genes: dict = {}
    for row in book["Table 4 - Annotated Exons"].iter_rows(values_only=True):
        cells = [str(c).strip() if c is not None else "" for c in row]
        gene, exon = cells[GENE], re.match(r"E(\d+)", cells[EXON])
        if gene not in ("BRCA1", "BRCA2") or not exon:
            continue
        entry = genes.setdefault(gene, {"exons": {}, "splice": {}})
        number = int(exon[1])
        if cells[PTC_TAG].startswith("PTC"):
            ptc = {"pvs1": code(cells[PTC_CODE]), "pm5_ptc": code(cells[PM5_CODE])}
            # The last exon is split by the codon of the premature stop: "PTC<p.I1855" is a
            # stop before codon 1855, "PTC>p.L1854" one after codon 1854.
            split = re.match(r"PTC([<>])p\.[A-Z](\d+)", cells[PTC_TAG])
            if split and split[1] == "<":
                ptc["before_codon"] = int(split[2])
            elif split:
                ptc["after_codon"] = int(split[2])
            entry["exons"].setdefault(number, []).append(ptc)
        for site, alleles, text, note in (
            (SITE_LEFT, ALLELES_LEFT, CODE_LEFT, NOTE_LEFT),
            (SITE_RIGHT, ALLELES_RIGHT, CODE_RIGHT, NOTE_RIGHT),
        ):
            if cells[site].startswith("c.") and cells[site].endswith(">") and cells[text]:
                for allele in re.split(r"[,\s]+", cells[alleles]):
                    if allele:
                        entry["splice"][cells[site] + allele] = code(cells[text]) | (
                            {"note": cells[note]} if cells[note] else {}
                        )
    header = (
        f"# ENIGMA BRCA1 and BRCA2 VCEP, Specifications Table 4, v{VERSION}: PVS1 and PM5_PTC\n"
        f"# codes by exon (MANE Select numbering) and by canonical splice-site change.\n"
        f"# Source: {DOC} (file {URL}).\n"
        f"# Curated content of the Clinical Genome Resource (www.clinicalgenome.org), CC0 1.0,\n"
        f"# accessed {date.today():%Y-%m-%d}. Generated by scripts/import_enigma_pvs1.py; do not\n"
        f"# edit by hand.\n"
    )
    body = {"version": VERSION, "source": DOC, "genes": genes}
    OUT.write_text(header + yaml.safe_dump(body, sort_keys=True, allow_unicode=True))
    for gene, entry in sorted(genes.items()):
        print(f"{gene}: {len(entry['exons'])} exons, {len(entry['splice'])} splice-site changes")
    print(f"written to {OUT}")


if __name__ == "__main__":
    main()
